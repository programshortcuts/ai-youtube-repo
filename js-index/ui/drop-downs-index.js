// ONLY get the TOP-LEVEL .drop-snips
const allDropSnips = document.querySelectorAll('.drop-snips')
const dropSnips = document.querySelectorAll(
    '.topics-container > .topic > .drop-snips'
);
export function initDropDowns() {
    // ==========================================
    // INITIALIZE DROPDOWN STATE
    // ==========================================
    allDropSnips.forEach(el => {
        // Only elements explicitly marked .show
        // should be visible on initial load.
        if (el.classList.contains("show")) {
            el.classList.remove("hide");
        } else {
            el.classList.remove("show");
            el.classList.add("hide");
        }
    });
    // Listen for mouse clicks
    document.addEventListener("click", handleToggle);
    // Listen for keyboard navigation
    document.addEventListener("keydown", handleToggle);
    function handleToggle(e) {
        let target;
        // ==========================================
        // KEYBOARD
        // ==========================================
        if (e.type === "keydown") {

            // Only respond to Enter or Space
            if (
                (e.key === "Enter" || e.key === " ") &&
                document.activeElement.classList.contains("drop-down")
            ) {
                e.preventDefault();
                target = document.activeElement;


            } else {
                return;
            }
        }
        // ==========================================
        // MOUSE CLICK
        // ==========================================
        else if (e.type === "click") {

            // Ignore clicks generated by keyboard
            if (e.detail === 0) return;

            // Find the .drop-down that was clicked
            target = e.target.closest(".drop-down");

            // If the click wasn't on a dropdown, do nothing
            if (!target) return;
        }
        // ==========================================
        // TOGGLE THE CORRESPONDING DROP-SNIPS
        // ==========================================
        toggleTopicSnips(target);
    }
}
function toggleTopicSnips(dropDown) {
    console.log("Clicked dropdown:", dropDown);
    // Find the .topic that contains this button
    const topic = dropDown.closest(".topic") || dropDown.closest(".topics");
    if (!topic) return;
    // if (topic.classList.contains('topics')) {
    //     const dropSnips = topic.querySelector('.drop-snips')
    //     console.log(dropSnips)
    // }
    // Find the .drop-snips that is DIRECTLY
    // associated with this .topic
    const topicSnips = topic.querySelector(
        // ":scope > .drop-snips"
        " .drop-snips"
    );
    console.log(topicSnips)
    // If this topic doesn't have a drop-snips,
    // there's nothing to toggle.
    if (!topicSnips) return;
    // Was this dropdown already open?
    const wasOpen = topicSnips.classList.contains("show");

    if (dropDown.classList.contains("topic-title") ||
        dropDown.classList.contains("topics")) {

        hideTopicSnips(dropDown);
    }
    if (wasOpen) {
        // It was open → close it
        topicSnips.classList.remove("show");
        topicSnips.classList.add("hide");
    } else {
        // It was closed → open it
        topicSnips.classList.remove("hide");
        topicSnips.classList.add("show");
    }
}
/*
=====================================================
HIDE OTHER TOP-LEVEL DROPDOWNS
=====================================================
*/
export function hideTopicSnips(currentTopic) {

    dropSnips.forEach(el => {

        // Don't hide the dropdown belonging
        // to the current top-level topic
        if (currentTopic.closest(".topic").contains(el)) {
            return;
        }

        // Hide all other TOP-LEVEL dropdowns
        el.classList.remove("show");
        el.classList.add("hide");
    });
}
